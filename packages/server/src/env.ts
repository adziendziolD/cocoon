/** uid of the sandbox user. */
const SANDBOX_UID = 1000;

/** First line of every file CoCoon writes – only files with it are ever overwritten or removed. */
export const ENV_FILE_MARKER = '# cocoon-managed: generated by CoCoon, changes are overwritten. Not part of the repository (.git/info/exclude).';

/** Exit codes of {@link WRITE_ENV_FILE_SCRIPT}. */
const EXIT = { missingDir: 10, noGit: 11, tracked: 12, foreign: 13 } as const;

/**
 * Writes (or removes) the .env file of one repository folder inside the sandbox. Variables: DIR (folder), REL (file path
 * inside it), STAGED (file with the new content; empty = remove our file), MARKER (first line of files we own).
 * The file is excluded from git (.git/info/exclude of the repository) *before* it is created, nothing is written into a
 * non-repository, over a tracked file, or over a file CoCoon did not create. Prints written | removed | unchanged.
 */
export const WRITE_ENV_FILE_SCRIPT = `
[ -z "$STAGED" ] || trap 'rm -f -- "$STAGED"' EXIT
cd "$DIR" 2>/dev/null || exit ${EXIT.missingDir}
ours() { [ -f "$REL" ] && [ ! -L "$REL" ] && [ "$(head -n 1 "$REL")" = "$MARKER" ]; }
if [ -z "$STAGED" ]; then
  if ours; then rm -f -- "$REL" && echo removed; else echo unchanged; fi
  exit 0
fi
git rev-parse --git-dir >/dev/null 2>&1 || exit ${EXIT.noGit}
if git ls-files --error-unmatch -- "$REL" >/dev/null 2>&1; then exit ${EXIT.tracked}; fi
if [ -e "$REL" ] || [ -L "$REL" ]; then ours || exit ${EXIT.foreign}; fi
if [ -f "$REL" ] && cmp -s "$STAGED" "$REL"; then echo unchanged; exit 0; fi
prefix="$(git rev-parse --show-prefix)"
exclude="$(git rev-parse --git-path info/exclude)"
mkdir -p "$(dirname "$exclude")"
grep -qxF "/$prefix$REL" "$exclude" 2>/dev/null || printf '/%s%s\\n' "$prefix" "$REL" >> "$exclude"
mkdir -p "$(dirname "$REL")"
umask 077
cat "$STAGED" > "$REL" && chmod 600 "$REL" && echo written
`;

interface Entry {
  name: string;
  value: string;
  target: EnvTarget;
  secret: boolean;
  proxyHost?: string;
  baseUrlEnv?: string;
  origin: EnvOrigin;
  overrides: EnvOrigin[];
}

interface Layer {
  origin: EnvOrigin;
  filePath?: string;
  vars: { name: string; value: string; rec: EnvVarRecord }[];
}

/** A credential-proxy route for variables "API key for host X" of one sandbox. */
export interface EnvRoute {
  name: string;
  upstream: string;
  secrets: Record<string, string>;
}

const UPPER_NAME = /^[A-Z][A-Z0-9_]*$/;

/**
 * .env injection: variables per workspace, repository and sandbox (encrypted at rest), merged for sandbox processes,
 * agents and .env files in the repository folders. Variables with a proxy host never enter the sandbox in plain text.
 */
export class EnvService implements SandboxHooks {
  private readonly vault: EnvVault;
  private readonly applied = new Map<string, { at: string; files: EnvFileStatus[] }>();

  constructor(
    private readonly store: Store,
    private readonly settings: SettingsService,
    private readonly sandboxes: SandboxManager,
    private readonly driver: SandboxDriver,
    private readonly egress: EgressManager,
    private readonly activity: ActivityLog,
    private readonly log: (msg: string, err?: unknown) => void,
  ) {
    this.vault = EnvVault.in(store.dataDir);
    egress.setEnvRoutes((sandbox) => this.routes(sandbox));
  }

  // ── editing ──────────────────────────────────────────────────────────────

  get(ref: EnvScopeRef): EnvScopeInfo {
    const { key, id, label } = this.scopeOf(ref);
    return this.info(ref.scope, id, key, label);
  }

  set(ref: EnvScopeRef, vars: EnvVarInput[], filePath?: string | null): EnvScopeInfo {
    const { key, id, label } = this.scopeOf(ref);
    const record: EnvScopeRecord = structuredClone(this.store.envScope(key) ?? { vars: {} });
    if (filePath !== undefined) {
      if (filePath === null || filePath === '' || filePath === DEFAULT_ENV_FILE) delete record.filePath;
      else if (!validEnvFilePath(filePath)) throw new CocoonError('bad_request', t('error.envFilePath', { path: filePath }));
      else record.filePath = filePath;
    }
    const now = new Date().toISOString();
    for (const input of vars) {
      if (isReservedEnvName(input.name)) throw new CocoonError('bad_request', t('error.envReserved', { name: input.name }));
      const existing = record.vars[input.name];
      if (input.value === undefined && !existing) throw new CocoonError('bad_request', t('error.envNoValue', { name: input.name }));
      if (input.value?.includes('\0')) throw new CocoonError('bad_request', t('error.envNoValue', { name: input.name }));

      const proxyHost = input.proxyHost === undefined ? existing?.proxyHost : input.proxyHost ? normalizeProxyHost(input.proxyHost) : undefined;
      if (input.proxyHost && !proxyHost) throw new CocoonError('bad_request', t('error.envProxyHost', { host: input.proxyHost }));
      if (proxyHost && !UPPER_NAME.test(input.name)) throw new CocoonError('bad_request', t('error.envProxyName', { name: input.name }));
      const baseUrlEnv = input.baseUrlEnv === undefined ? existing?.baseUrlEnv : input.baseUrlEnv || undefined;
      if (baseUrlEnv && isReservedEnvName(baseUrlEnv)) throw new CocoonError('bad_request', t('error.envReserved', { name: baseUrlEnv }));

      record.vars[input.name] = {
        enc: input.value === undefined ? existing!.enc : this.vault.encrypt(`${key}/${input.name}`, input.value),
        target: input.target ?? existing?.target ?? 'env',
        // A proxied value is a credential by definition.
        secret: proxyHost ? true : (input.secret ?? existing?.secret ?? true),
        proxyHost,
        baseUrlEnv: proxyHost ? baseUrlEnv : undefined,
        updatedAt: input.value === undefined ? (existing?.updatedAt ?? now) : now,
      };
    }
    return this.save(ref.scope, id, key, label, record, vars.length);
  }

  unset(ref: EnvScopeRef, names: string[]): EnvScopeInfo {
    const { key, id, label } = this.scopeOf(ref);
    const record: EnvScopeRecord = structuredClone(this.store.envScope(key) ?? { vars: {} });
    let removed = 0;
    for (const name of names) if (delete record.vars[name]) removed++;
    return this.save(ref.scope, id, key, label, record, removed);
  }

  import(params: MethodParams<'env.import'>): MethodResult<'env.import'> {
    const parsed = parseDotenv(params.content);
    const usable = parsed.vars.filter((v) => !isReservedEnvName(v.name));
    const errors = [...parsed.errors, ...parsed.vars.filter((v) => isReservedEnvName(v.name)).map((v) => ({ line: 0, message: t('error.envReserved', { name: v.name }) }))];
    const ref = { scope: params.scope, id: params.id };
    // Validate and store first; only then drop what the file no longer mentions.
    let scope = this.set(ref, usable.map((v) => ({ name: v.name, value: v.value, target: params.target, secret: params.secret })));
    if (params.replace) {
      const keep = new Set(usable.map((v) => v.name));
      const stale = scope.vars.map((v) => v.name).filter((name) => !keep.has(name));
      if (stale.length) scope = this.unset(ref, stale);
    }
    return { scope, imported: usable.map((v) => v.name), errors };
  }

  // ── merging ──────────────────────────────────────────────────────────────

  /** The variables a sandbox (and an agent of `agentKind`) gets, with origins. Values only for non-secret variables. */
  resolve(sandboxId: string, agentKind?: string): ResolvedEnv {
    const record = this.sandboxes.record(sandboxId);
    const entries = this.merge(record, reposOf(record));
    const canProxy = this.canProxy(record);
    const vars: ResolvedEnvVar[] = [...entries.values()].map((e) => ({
      name: e.name,
      target: e.target,
      secret: e.secret,
      value: e.secret ? undefined : e.value,
      proxyHost: e.proxyHost,
      origin: e.origin,
      overrides: e.overrides,
      skipped: e.proxyHost && !canProxy ? t('env.skippedProxy') : undefined,
    }));
    const profile = agentKind ? this.settings.get().agents[agentKind] : undefined;
    if (agentKind && profile) {
      const origin: EnvOrigin = { scope: 'agent', id: agentKind, label: agentKind };
      // The agent type's own variables are plain settings; their values are not echoed here.
      for (const name of Object.keys(profile.env)) {
        const index = vars.findIndex((v) => v.name === name);
        const previous = vars[index];
        const entry: ResolvedEnvVar = { name, target: 'env', secret: true, origin, overrides: previous ? [...previous.overrides, previous.origin] : [] };
        if (previous) vars[index] = entry;
        else vars.push(entry);
      }
    }
    vars.sort((a, b) => a.name.localeCompare(b.name));
    const applied = this.applied.get(sandboxId);
    return { sandboxId, agentKind, vars, files: applied?.files ?? [], appliedAt: applied?.at };
  }

  /** Environment variables for processes in the sandbox (agents, commands): workspace → repositories → sandbox. */
  injectedEnv(record: SandboxRecord): Record<string, string> {
    return this.build(record, this.merge(record, reposOf(record))).env;
  }

  /** Credential-proxy routes of a sandbox: one per host, holding the real values of its proxied variables. */
  routes(sandboxId: string): EnvRoute[] {
    const full = this.store.sandbox(sandboxId);
    if (!full || !this.canProxy(full)) return [];
    const byHost = new Map<string, EnvRoute>();
    for (const entry of this.merge(full, reposOf(full)).values()) {
      if (!entry.proxyHost) continue;
      const route = byHost.get(entry.proxyHost) ?? { name: routeName(full.id, entry.proxyHost), upstream: proxyHostUrl(entry.proxyHost), secrets: {} };
      route.secrets[entry.name] = entry.value;
      byHost.set(entry.proxyHost, route);
    }
    return [...byHost.values()];
  }

  // ── injection ────────────────────────────────────────────────────────────

  /** Before an agent starts: writes the current .env files and waits until the proxy knows the sandbox's routes. */
  async prepare(sandboxId: string): Promise<void> {
    await this.applyFiles(sandboxId).catch((err) => this.fileFailed(sandboxId, err));
    if (this.routes(sandboxId).length) {
      this.egress.writePolicy();
      await this.egress.awaitPolicy();
    }
  }

  /** Writes the .env files of all repository folders (variables with target "file" or "both"). */
  async applyFiles(sandboxId: string): Promise<EnvFileStatus[]> {
    const record = this.sandboxes.record(sandboxId);
    const handle = this.sandboxes.runningHandle(sandboxId);
    const repos = reposOf(record);
    const folders: SandboxRepo[] = repos.length ? repos : [{ url: '', path: '' }];
    const global = this.merge(record, repos);
    const files: EnvFileStatus[] = [];
    for (const folder of folders) {
      const layers = this.layers(record, repos.length ? [folder] : []);
      const path = [...layers].reverse().find((l) => l.filePath)?.filePath ?? DEFAULT_ENV_FILE;
      const merged = this.mergeLayers(layers);
      // Proxied variables are sandbox-wide (one route per host): a repository cannot bring its own value for them.
      for (const [name, entry] of merged) if (entry.proxyHost && global.has(name)) merged.set(name, global.get(name)!);
      const fileVars = this.build(record, merged).fileVars;
      files.push(await this.writeFile(handle, record, folder.path, path, fileVars));
    }
    this.applied.set(sandboxId, { at: new Date().toISOString(), files });
    return files;
  }

  async created(record: SandboxRecord): Promise<void> {
    await this.applyFiles(record.id).catch((err) => this.fileFailed(record.id, err));
  }

  async started(record: SandboxRecord): Promise<void> {
    await this.applyFiles(record.id).catch((err) => this.fileFailed(record.id, err));
  }

  private async writeFile(handle: string, record: SandboxRecord, folder: string, path: string, vars: { name: string; value: string }[]): Promise<EnvFileStatus> {
    const dir = folder ? `${record.workdir}/${folder}` : record.workdir;
    const base = { folder, path, vars: vars.length };
    let staged = '';
    if (vars.length) {
      const name = `envfile-${randomBytes(8).toString('hex')}`;
      staged = `${STAGING_DIR}/${name}`;
      await this.driver.putArchive(handle, STAGING_DIR, singleFileTar(name, Buffer.from(renderDotenv(vars, ENV_FILE_MARKER)), { uid: SANDBOX_UID, gid: SANDBOX_UID, mode: 0o600 }));
    }
    const res = await this.driver.exec(handle, ['sh', '-c', WRITE_ENV_FILE_SCRIPT], {
      env: { DIR: dir, REL: path, STAGED: staged, MARKER: ENV_FILE_MARKER },
      timeoutMs: 30_000,
    });
    const shown = folder ? `${folder}/${path}` : path;
    switch (res.exitCode) {
      case 0: {
        const status = res.stdout.trim() as EnvFileStatus['status'];
        return { ...base, status: ['written', 'removed', 'unchanged'].includes(status) ? status : 'unchanged' };
      }
      case EXIT.tracked: return { ...base, status: 'skipped', message: t('env.fileTracked', { path: shown }) };
      case EXIT.foreign: return { ...base, status: 'skipped', message: t('env.fileForeign', { path: shown }) };
      case EXIT.noGit: return { ...base, status: 'skipped', message: t('env.fileNoGit') };
      default: return { ...base, status: 'error', message: res.stderr.trim().slice(0, 300) || `exit ${res.exitCode}` };
    }
  }

  private fileFailed(sandboxId: string, err: unknown): void {
    const sandbox = this.store.sandbox(sandboxId);
    this.log('writing .env files failed', err);
    this.activity.add('warn', 'activity.envFileFailed', { sandbox: sandbox?.name ?? sandboxId, error: (err as Error).message.slice(0, 300) }, { sandboxId });
  }

  // ── internals ────────────────────────────────────────────────────────────

  private canProxy(record: Pick<SandboxRecord, 'network'>): boolean {
    return record.network !== 'none' && this.settings.get().egress.credentialProxy;
  }

  /** Splits merged variables into process environment and .env file lines; proxied ones become placeholders. */
  private build(record: SandboxRecord, entries: Map<string, Entry>) {
    const env: Record<string, string> = {};
    const fileVars: { name: string; value: string }[] = [];
    const baseUrls: { name: string; value: string; target: EnvTarget }[] = [];
    const canProxy = this.canProxy(record);
    for (const e of entries.values()) {
      let value = e.value;
      if (e.proxyHost) {
        if (!canProxy) continue; // never in plain text
        value = placeholderFor(record.proxyToken, e.name);
        baseUrls.push({
          name: e.baseUrlEnv ?? defaultBaseUrlEnv(e.name),
          value: this.egress.credentialUrl(record, routeName(record.id, e.proxyHost)),
          target: e.target,
        });
      }
      if (e.target !== 'file') env[e.name] = value;
      if (e.target !== 'env') fileVars.push({ name: e.name, value });
    }
    // A variable the user defined explicitly wins over a derived base URL of the same name.
    for (const b of baseUrls) {
      if (entries.has(b.name)) continue;
      if (b.target !== 'file') env[b.name] = b.value;
      if (b.target !== 'env') fileVars.push({ name: b.name, value: b.value });
    }
    return { env, fileVars };
  }

  private merge(record: SandboxRecord, repos: SandboxRepo[]): Map<string, Entry> {
    return this.mergeLayers(this.layers(record, repos));
  }

  private mergeLayers(layers: Layer[]): Map<string, Entry> {
    const result = new Map<string, Entry>();
    for (const layer of layers) {
      for (const { name, value, rec } of layer.vars) {
        const previous = result.get(name);
        result.set(name, {
          name,
          value,
          target: rec.target,
          secret: rec.secret,
          proxyHost: rec.proxyHost,
          baseUrlEnv: rec.baseUrlEnv,
          origin: layer.origin,
          overrides: previous ? [...previous.overrides, previous.origin] : [],
        });
      }
    }
    return result;
  }

  /** Levels in order of precedence (weakest first): workspace, the given repositories, sandbox. */
  private layers(record: SandboxRecord, repos: SandboxRepo[]): Layer[] {
    const layers: Layer[] = [];
    const workspace = record.workspaceId ? this.store.workspace(record.workspaceId) : undefined;
    if (workspace) layers.push(this.layer('workspace', workspace.id, workspace.name, `workspace:${workspace.id}`));
    const seen = new Set<string>();
    for (const repo of repos) {
      const id = normalizeRepoUrl(repo.url);
      if (!id || seen.has(id)) continue;
      seen.add(id);
      layers.push(this.layer('repo', id, id, `repo:${id}`));
    }
    layers.push(this.layer('sandbox', record.id, record.name, `sandbox:${record.id}`));
    return layers.filter((l) => l.vars.length || l.filePath);
  }

  private layer(scope: 'workspace' | 'repo' | 'sandbox', id: string, label: string, key: string): Layer {
    const record = this.store.envScope(key);
    const vars: Layer['vars'] = [];
    for (const [name, rec] of Object.entries(record?.vars ?? {})) {
      const value = this.vault.decrypt(`${key}/${name}`, rec.enc);
      if (value === undefined) this.log(t('error.envValueUnreadable', { name }));
      else vars.push({ name, value, rec });
    }
    return { origin: { scope, id, label }, filePath: record?.filePath, vars };
  }

  private scopeOf(ref: EnvScopeRef): { key: string; id: string; label: string } {
    switch (ref.scope) {
      case 'workspace': {
        const workspace = this.store.workspace(ref.id);
        if (!workspace) throw notFound('Workspace', ref.id);
        return { key: `workspace:${workspace.id}`, id: workspace.id, label: workspace.name };
      }
      case 'sandbox': {
        const sandbox = this.store.sandbox(ref.id);
        if (!sandbox) throw notFound('Sandbox', ref.id);
        return { key: `sandbox:${sandbox.id}`, id: sandbox.id, label: sandbox.name };
      }
      case 'repo': {
        const id = normalizeRepoUrl(ref.id);
        if (!id.includes('/')) throw new CocoonError('bad_request', t('error.notFound', { what: 'Repository', id: ref.id }));
        return { key: `repo:${id}`, id, label: id };
      }
    }
  }

  private info(scope: EnvScopeRef['scope'], id: string, key: string, label: string): EnvScopeInfo {
    const record = this.store.envScope(key);
    const vars: EnvVar[] = Object.entries(record?.vars ?? {})
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([name, rec]) => ({
        name,
        target: rec.target,
        secret: rec.secret,
        value: rec.secret ? undefined : this.vault.decrypt(`${key}/${name}`, rec.enc),
        proxyHost: rec.proxyHost,
        baseUrlEnv: rec.baseUrlEnv,
        updatedAt: rec.updatedAt,
      }));
    return { scope, id, label, filePath: record?.filePath, vars };
  }

  private save(scope: EnvScopeRef['scope'], id: string, key: string, label: string, record: EnvScopeRecord, count: number): EnvScopeInfo {
    this.store.putEnvScope(key, record);
    this.egress.writePolicy();
    this.activity.add('info', 'activity.envChanged', { level: scope, label, count });
    return this.info(scope, id, key, label);
  }
}

/** Route name for the proxied variables of a sandbox and host; path-safe (no "/" or ":"), http hosts are told apart. */
export const routeName = (sandboxId: string, host: string) => `env-${sandboxId}-${host.replace(/^http:\/\//, 'http-').replace(/:/g, '-port-')}`;
